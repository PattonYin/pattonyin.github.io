#!/usr/bin/env python3
"""Generate distinct static URLs for Cloudflare's path-based page reports.

Run after changing the page shells or the project/robot lists. Generated HTML
is committed alongside the site, so static hosting needs no build service.
"""

import argparse
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def render_page(template, kind, slug, entry):
    page = template.replace('<body>', f'<body data-{kind}="{html.escape(slug)}">')
    title = html.escape(f"{entry['title']} | Jiyang (Patton) Yin")
    description = html.escape(entry['description'])
    page = re.sub(r'<title>.*?</title>', lambda _: f'<title>{title}</title>', page)
    for attribute, name, value in [
        ('name', 'description', description),
        ('property', 'og:title', title),
        ('property', 'og:description', description),
    ]:
        page = re.sub(
            rf'(<meta {attribute}="{name}" content=")[^"]*(">)',
            lambda match: match[1] + value + match[2], page,
        )
    # All generated pages are one directory below the site root. Keep fragments
    # local so the SVG icons, skip links, and section outline continue to work.
    page = re.sub(
        r'\b(href|src)="(?![#/]|[a-zA-Z][a-zA-Z\d+.-]*:)([^"]+)"',
        lambda match: f'{match[1]}="../{match[2]}"', page,
    )
    return page.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by tools/generate_pages.py; edit the root page shell instead. -->', 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated pages need updating')
    args = parser.parse_args()
    projects = json.loads((ROOT / 'portfolio/projects.json').read_text(encoding='utf-8'))
    robots = json.loads((ROOT / 'data/rollouts.json').read_text(encoding='utf-8'))
    stale = []
    for directory, kind, entries in [
        ('portfolio', 'project', {project['slug']: project for project in projects}),
        ('rollouts', 'robot', robots),
    ]:
        template = (ROOT / f'{directory}.html').read_text(encoding='utf-8')
        for slug, entry in entries.items():
            if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
                raise ValueError(f'Invalid page slug: {slug}')
            path = ROOT / directory / f'{slug}.html'
            output = render_page(template, kind, slug, entry)
            if args.check:
                if not path.exists() or path.read_text(encoding='utf-8') != output:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.parent.mkdir(exist_ok=True)
                path.write_text(output, encoding='utf-8', newline='\n')
                print(path.relative_to(ROOT))
    if stale:
        parser.exit(1, 'Run python tools/generate_pages.py to update: ' + ', '.join(stale) + '\n')


if __name__ == '__main__':
    main()
